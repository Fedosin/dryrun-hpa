#!/usr/bin/env bash
# Copies the HPA controller and the helpers it needs from the Kubernetes
# release pinned in hack/upstream.lock into internal/upstream, then applies
# the local patch series from hack/upstream-patches.
#
# Usage:
#   hack/sync-upstream.sh             copy upstream files and apply all patches
#   hack/sync-upstream.sh --no-patches  copy upstream files only
#   hack/sync-upstream.sh diff        print the changes in internal/upstream that
#                                     are not covered by the patch series yet;
#                                     redirect it to a new patch file
#
# Upstream package paths are mirrored: k8s.io/kubernetes/pkg/<path> becomes
# <module>/internal/upstream/<path>. Files under internal/upstream that are not
# listed in FILES (shims, dryrun_hooks.go) belong to this project and are never
# touched.

set -o errexit
set -o nounset
set -o pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
# shellcheck source=/dev/null
source "${ROOT}/hack/upstream.lock"
MODULE="$(cd "${ROOT}" && go list -m)"
DEST="${ROOT}/internal/upstream"
PATCHES="${ROOT}/hack/upstream-patches"

FILES=(
  controller/podautoscaler/doc.go
  controller/podautoscaler/horizontal.go
  controller/podautoscaler/horizontal_test.go
  controller/podautoscaler/hpa_selector_store.go
  controller/podautoscaler/hpa_selector_store_test.go
  controller/podautoscaler/rate_limiters.go
  controller/podautoscaler/replica_calculator.go
  controller/podautoscaler/replica_calculator_test.go
  controller/podautoscaler/metrics/client.go
  controller/podautoscaler/metrics/client_test.go
  controller/podautoscaler/metrics/interfaces.go
  controller/podautoscaler/metrics/utilization.go
  controller/podautoscaler/metrics/utilization_test.go
  controller/podautoscaler/monitor/metrics.go
  controller/podautoscaler/monitor/monitor.go
  controller/util/selectors/bimultimap.go
  controller/util/selectors/bimultimap_test.go
  controller/util/consistency/consistency.go
  controller/util/consistency/consistency_test.go
  api/v1/pod/util.go
  apis/autoscaling/v2/defaults.go
)

# Feature gates referenced by the copied code. Their specs are extracted from
# upstream so defaults always match the pinned release.
FEATURES=(
  HPAConfigurableTolerance
  HPAGeneration
  HPAOptimizedSelectorStore
  HPAScaleToZero
  PodLevelResources
  PodObservedGenerationTracking
  RestartAllContainersOnContainerExits
  StaleControllerConsistencyHPA
)

upstream_dir() {
  local tmp
  tmp="$(mktemp -d)"
  (cd "${tmp}" && GOFLAGS=-mod=mod GO111MODULE=on go mod download -json "k8s.io/kubernetes@${KUBERNETES_VERSION}") |
    sed -n 's/.*"Dir": "\(.*\)",/\1/p'
  rm -rf "${tmp}"
}

rewrite_imports() {
  sed -i \
    -e 's#"k8s.io/kubernetes/pkg/api/legacyscheme"#legacyscheme "k8s.io/client-go/kubernetes/scheme"#' \
    -e '/"k8s.io\/kubernetes\/pkg\/apis\/[a-z]*\/install"/d' \
    -e "s#\"k8s.io/kubernetes/test/utils/ktesting\"#\"${MODULE}/internal/upstream/test/utils/ktesting\"#" \
    -e "s#\"k8s.io/kubernetes/pkg/#\"${MODULE}/internal/upstream/#" \
    "$1"
}

generate_features() {
  local src="$1" out="$2"
  mkdir -p "$(dirname "${out}")"
  {
    cat "${ROOT}/hack/boilerplate.go.txt"
    cat <<EOF

// Code generated by hack/sync-upstream.sh from k8s.io/kubernetes ${KUBERNETES_VERSION}
// pkg/features/kube_features.go. DO NOT EDIT.

// Package features registers the Kubernetes feature gates used by the copied
// HPA controller in the default apiserver feature gate, with the same
// versioned defaults as kube-controller-manager ${KUBERNETES_VERSION}.
package features

import (
	"k8s.io/apimachinery/pkg/util/version"
	utilruntime "k8s.io/apimachinery/pkg/util/runtime"
	utilfeature "k8s.io/apiserver/pkg/util/feature"
	"k8s.io/component-base/featuregate"
)

const (
EOF
    for f in "${FEATURES[@]}"; do
      printf '\t%s featuregate.Feature = "%s"\n' "${f}" "${f}"
    done
    printf ')\n\nvar defaultVersionedKubernetesFeatureGates = map[featuregate.Feature]featuregate.VersionedSpecs{\n'
    for f in "${FEATURES[@]}"; do
      awk -v name="${f}" '
        $0 ~ "^\t" name ": \\{$" { on = 1 }
        on { print }
        on && $0 ~ "^\t},$" { exit }
      ' "${src}/pkg/features/kube_features.go"
    done
    cat <<'EOF'
}

func init() {
	utilruntime.Must(utilfeature.DefaultMutableFeatureGate.AddVersioned(defaultVersionedKubernetesFeatureGates))
}
EOF
  } > "${out}"
  gofmt -w "${out}"
}

copy_pristine() {
  local src="$1" dst="$2"
  for f in "${FILES[@]}"; do
    mkdir -p "$(dirname "${dst}/${f}")"
    cp "${src}/pkg/${f}" "${dst}/${f}"
    chmod 644 "${dst}/${f}"
    rewrite_imports "${dst}/${f}"
  done
  generate_features "${src}" "${dst}/features/kube_features.go"
}

apply_patches() {
  local dir="$1"
  shopt -s nullglob
  for p in "${PATCHES}"/*.patch; do
    echo "Applying $(basename "${p}")" >&2
    patch --quiet --forward --no-backup-if-mismatch -p1 -d "${dir}" < "${p}"
  done
}

SRC="$(upstream_dir)"
if [[ -z "${SRC}" ]]; then
  echo "unable to download k8s.io/kubernetes@${KUBERNETES_VERSION}" >&2
  exit 1
fi

case "${1:-}" in
  diff)
    work="$(mktemp -d)"
    trap 'rm -rf "${work}"' EXIT
    mkdir -p "${work}/a/internal/upstream" "${work}/b/internal/upstream"
    copy_pristine "${SRC}" "${work}/a/internal/upstream"
    apply_patches "${work}/a"
    for f in "${FILES[@]}"; do
      mkdir -p "$(dirname "${work}/b/internal/upstream/${f}")"
      cp "${DEST}/${f}" "${work}/b/internal/upstream/${f}"
    done
    cp "${work}/a/internal/upstream/features/kube_features.go" "${work}/b/internal/upstream/features/kube_features.go" 2>/dev/null ||
      { mkdir -p "${work}/b/internal/upstream/features"; cp "${work}/a/internal/upstream/features/kube_features.go" "${work}/b/internal/upstream/features/"; }
    (cd "${work}" && diff -ruN a b) | sed -E 's/^(---|\+\+\+) ([^\t]+)\t.*/\1 \2/' || true
    ;;
  --no-patches)
    copy_pristine "${SRC}" "${DEST}"
    ;;
  "")
    copy_pristine "${SRC}" "${DEST}"
    apply_patches "${ROOT}"
    ;;
  *)
    echo "unknown argument: $1" >&2
    exit 2
    ;;
esac
